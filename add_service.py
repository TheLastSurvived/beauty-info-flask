        salon_map = {}
        for salon in salons:
            # Нормализуем название для поиска
            normalized = salon.name.lower().strip()
            salon_map[normalized] = salon.id
            
            # Добавляем альтернативные варианты
            if salon.name == "Массаж":
                salon_map["массаж (ул. куйбышева)"] = salon.id
            elif salon.name == "Массажный салон":
                salon_map["массажный салон (тимирязева)"] = salon.id
            elif salon.name == "Депиляция":
                salon_map["депиляция (ленина)"] = salon.id
        
        print(f"Найдено салонов в БД: {len(salons)}")
        print("Сопоставление названий:")
        for name, sid in salon_map.items():
            print(f"  '{name}' -> ID: {sid}")
        
        total_added = 0
        total_skipped = 0
        
        # Для каждого салона в наших данных
        for salon_name, data in SERVICES_DATA.items():
            # Ищем ID салона
            normalized_key = salon_name.lower().strip()
            salon_id = salon_map.get(normalized_key)
            
            # Если не нашли, пробуем искать по частичному совпадению
            if not salon_id:
                for key in salon_map:
                    if salon_name.lower() in key or key in salon_name.lower():
                        salon_id = salon_map[key]
                        print(f"Частичное совпадение: '{salon_name}' -> '{key}' (ID: {salon_id})")
                        break
            
            if not salon_id:
                print(f"❌ Салон не найден: {salon_name}")
                total_skipped += len(data['services'])
                continue
            
            print(f"\n✅ Обработка салона: {salon_name} (ID: {salon_id})")
            
            # Получаем существующие услуги для этого салона
            existing_services = {
                (s.name.lower(), s.price): s.id 
                for s in Service.query.filter_by(salon_id=salon_id).all()
            }
            
            added = 0
            skipped = 0
            
            # Добавляем услуги
            for service_data in data['services']:
                # Проверяем, существует ли уже такая услуга
                key = (service_data['name'].lower(), service_data['price'])
                
                if key in existing_services:
                    print(f"  ⏭️ Пропущено (уже есть): {service_data['name']} - {service_data['price']} BYN")
                    skipped += 1
                    continue
                
                # Создаем новую услугу
                service = Service(
                    salon_id=salon_id,
                    category=service_data['category'],
                    name=service_data['name'],
                    price=service_data['price'],
                    description=service_data.get('description', '')
                )
                db.session.add(service)
                added += 1
                print(f"  ✅ Добавлено: {service_data['name']} - {service_data['price']} BYN")
            
            total_added += added
            total_skipped += skipped
            print(f"  Итого для салона: +{added} услуг, пропущено: {skipped}")
        
        # Сохраняем изменения
        db.session.commit()
        
        print("\n" + "="*50)
        print(f"ГОТОВО!")
        print(f"✅ Добавлено услуг: {total_added}")
        print(f"⏭️ Пропущено (уже были): {total_skipped}")
        print("="*50)

