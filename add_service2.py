# Сопоставление названий салонов
SALON_NAME_MAPPING = {
    "Лаквин": ["лаквин", "lakvin"],
    "Мир красоты": ["мир красоты", "mir_krasoty", "beauty_world"],
    "Baunty": ["baunty"],
    "Студия эстетической косметологии": ["студия эстетической косметологии", "olga_sokolyan"],
    "RedMak": ["redmak", "redmak_epil"],
    "Персона": ["персона", "persona"],
}

def add_new_services():
    """Добавление новых услуг из второго файла"""
    
    with app.app_context():
        # Получаем все салоны из БД
        salons = Salon.query.all()
        
        # Создаем словарь для поиска салонов
        salon_map = {}
        for salon in salons:
            normalized = salon.name.lower().strip()
            salon_map[normalized] = salon.id
            
            # Также добавляем альтернативные варианты
            salon_map[salon.name.lower()] = salon.id
        
        print(f"Найдено салонов в БД: {len(salons)}")
        print("\nСписок салонов в БД:")
        for salon in salons:
            print(f"  - '{salon.name}' (ID: {salon.id})")
        
        total_added = 0
        total_skipped = 0
        
        # Для каждого салона в наших данных
        for salon_name, data in NEW_SERVICES_DATA.items():
            # Ищем ID салона
            salon_id = None
            
            # Прямое совпадение
            if salon_name.lower() in salon_map:
                salon_id = salon_map[salon_name.lower()]
            else:
                # Поиск по альтернативным названиям
                aliases = SALON_NAME_MAPPING.get(salon_name, [])
                for alias in aliases:
                    if alias.lower() in salon_map:
                        salon_id = salon_map[alias.lower()]
                        break
                
                # Поиск по частичному совпадению
                if not salon_id:
                    for db_name, db_id in salon_map.items():
                        if salon_name.lower() in db_name or db_name in salon_name.lower():
                            salon_id = db_id
                            print(f"  Частичное совпадение: '{salon_name}' -> '{db_name}'")
                            break
            
            if not salon_id:
                print(f"\n❌ Салон не найден: {salon_name}")
                total_skipped += len(data['services'])
                continue
            
            print(f"\n✅ Обработка салона: {salon_name} (ID: {salon_id})")
            
            # Получаем существующие услуги для этого салона
            existing_services = {
                (s.name.lower(), s.price): s.id 
                for s in Service.query.filter_by(salon_id=salon_id).all()
            }
            
            added = 0
            skipped = 0
            
            # Добавляем услуги
            for service_data in data['services']:
                # Проверяем, существует ли уже такая услуга
                key = (service_data['name'].lower(), service_data['price'])
                
                if key in existing_services:
                    skipped += 1
                    continue
                
                # Создаем новую услугу
                service = Service(
                    salon_id=salon_id,
                    category=service_data['category'],
                    name=service_data['name'],
                    price=service_data['price'],
                    description=service_data.get('description', '')
                )
                db.session.add(service)
                added += 1
                print(f"  ✅ Добавлено: {service_data['name']} - {service_data['price']} BYN")
            
            total_added += added
            total_skipped += skipped
            print(f"  Итого для салона: +{added} услуг, пропущено: {skipped}")
        
        # Сохраняем изменения
        db.session.commit()
        
        print("\n" + "="*50)
        print(f"ГОТОВО!")
        print(f"✅ Добавлено услуг: {total_added}")
        print(f"⏭️ Пропущено (уже были): {total_skipped}")
        print("="*50)

if __name__ == "__main__":
    add_new_services()